export type CopyKey = keyof (typeof copy)['en'];

export function translate(locale: Locale, key: CopyKey): string {
  return copy[locale][key];
}

export function formatCopy(
  locale: Locale,
  key: CopyKey,
  values: Record<string, string | number>,
): string {
  return translate(locale, key).replaceAll(/\{([^}]+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

function browserLanguage(): string {
  if (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage) {
    return chrome.i18n.getUILanguage();
  }
  return typeof navigator === 'undefined' ? 'en' : navigator.language;
}

export function defaultLocale(language?: string): Locale {
  return (language ?? browserLanguage()).toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}
